def load_dotenv_file(path: Path) -> None:
    if not path.exists():
        return

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if not key:
            continue
        if value.startswith(("'", '"')) and value.endswith(("'", '"')) and len(value) >= 2:
            value = value[1:-1]
        os.environ.setdefault(key, value)


def parse_int_env(name: str, default: int) -> int:
    raw = os.getenv(name, str(default)).strip()
    try:
        value = int(raw)
        if value <= 0:
            raise ValueError
        return value
    except ValueError:
        LOGGER.warning("%s invalid (%s), fallback to %s", name, raw, default)
        return default


def parse_nonnegative_int_env(name: str, default: int) -> int:
    raw = os.getenv(name, str(default)).strip()
    try:
        value = int(raw)
        if value < 0:
            raise ValueError
        return value
    except ValueError:
        LOGGER.warning("%s invalid (%s), fallback to %s", name, raw, default)
        return default


def parse_bool_env(name: str, default: bool) -> bool:
    raw = os.getenv(name)
    if raw is None:
        return default
    text = raw.strip().lower()
    if text in {"1", "true", "yes", "y", "on"}:
        return True
    if text in {"0", "false", "no", "n", "off"}:
        return False
    LOGGER.warning("%s invalid (%s), fallback to %s", name, raw, default)
    return default


def get_timezone(tz_name: str) -> timezone:
    try:
        return ZoneInfo(tz_name)
    except ZoneInfoNotFoundError:
        if tz_name == DEFAULT_TIMEZONE:
            return timezone(timedelta(hours=8), name=tz_name)
        if tz_name.upper() == "UTC":
            return timezone.utc
        raise RuntimeError(f"Invalid TIMEZONE: {tz_name}")


def safe_endpoint_label(url: str) -> str:
    parsed = urlparse(url)
    return parsed.netloc or "unknown-host"


def normalize_url(url: str) -> str:
    value = (url or "").strip()
    if not value:
        return ""
    parsed = urlparse(value)
    tracking_keys = {
        "utm_source",
        "utm_medium",
        "utm_campaign",
        "utm_term",
        "utm_content",
        "fbclid",
        "gclid",
        "spm",
        "from",
        "source",
    }
    query = [
        (key, val)
        for key, val in parse_qsl(parsed.query, keep_blank_values=True)
        if key.lower() not in tracking_keys
    ]
    return urlunparse(
        (
            parsed.scheme.lower(),
            parsed.netloc.lower(),
            parsed.path.rstrip("/"),
            "",
            urlencode(query, doseq=True),
            "",
        )
    )


def clean_text(value: Any) -> str:
    text = str(value or "")
    text = text.replace("\r", "\n")
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def truncate_text(text: str, max_len: int) -> str:
    text = clean_text(text)
    if max_len <= 0:
        return ""
    if len(text) <= max_len:
        return text
    if max_len == 1:
        return text[:1]
    return text[: max_len - 1].rstrip() + "…"


def http_post_json(
    url: str,
    payload: dict[str, Any],
    headers: dict[str, str] | None = None,
    timeout_seconds: int | None = None,
    retry_count: int = 0,
    retry_timeout_seconds: int | None = None,
) -> dict[str, Any]:
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req_headers = {"Content-Type": "application/json"}
    if headers:
        req_headers.update(headers)

    timeout_value = timeout_seconds or parse_int_env("HTTP_TIMEOUT_SECONDS", DEFAULT_HTTP_TIMEOUT_SECONDS)
    retry_timeout_value = retry_timeout_seconds or timeout_value
    attempts = max(retry_count, 0) + 1
    last_exc: Exception | None = None

    for attempt in range(1, attempts + 1):
        attempt_timeout = timeout_value if attempt == 1 else retry_timeout_value
        request = Request(url=url, data=data, headers=req_headers, method="POST")
        try:
            with urlopen(request, timeout=attempt_timeout) as response:
                body = response.read().decode("utf-8", errors="replace")
            break
        except HTTPError as exc:
            body = exc.read().decode("utf-8", errors="replace") if exc.fp else ""
            raise RuntimeError(
                f"HTTP {exc.code} calling endpoint={safe_endpoint_label(url)}: {body[:200]}"
            ) from exc
        except TimeoutError as exc:
            last_exc = exc
            if attempt < attempts:
                LOGGER.warning(
                    "Request timed out calling endpoint=%s after %ss, retry %s/%s",
                    safe_endpoint_label(url),
                    attempt_timeout,
                    attempt,
                    retry_count,
                )
                continue
            raise RuntimeError(
                f"Request timed out calling endpoint={safe_endpoint_label(url)} after {attempt_timeout}s"
            ) from exc
        except URLError as exc:
            last_exc = exc
            if attempt < attempts:
                LOGGER.warning(
                    "Network error calling endpoint=%s, retry %s/%s: %s",
                    safe_endpoint_label(url),
                    attempt,
                    retry_count,
                    exc,
                )
                continue
            raise RuntimeError(f"Network error calling endpoint={safe_endpoint_label(url)}: {exc}") from exc
    else:
        raise RuntimeError(f"Request failed calling endpoint={safe_endpoint_label(url)}: {last_exc}")

    try:
        return json.loads(body) if body else {}
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"Invalid JSON response from endpoint={safe_endpoint_label(url)}: {body[:200]}"
        ) from exc


def ensure_list_of_strings(value: Any) -> list[str]:
    if isinstance(value, str):
        text = clean_text(value)
        return [text] if text else []
    if isinstance(value, list):
        out: list[str] = []
        for item in value:
            text = clean_text(item)
            if text:
                out.append(text)
        return out
    return []


def read_candidates_file(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise RuntimeError(f"Invalid JSON structure: {path.name}")
    items = data.get("curated_items", data.get("items"))
    if not isinstance(items, list):
        raise RuntimeError(f"Invalid JSON curated_items/items list: {path.name}")
    return data


def find_candidates_json(data_dir: Path, target_date: str) -> tuple[dict[str, Any], Path, bool]:
    expected_file = data_dir / f"{target_date}.json"
    if expected_file.exists():
        return read_candidates_file(expected_file), expected_file, False

    candidates = sorted(data_dir.glob("*.json"), reverse=True)
    if not candidates:
        raise RuntimeError(f"No candidates JSON found in {data_dir}")

    for path in candidates[:FALLBACK_SCAN_DAYS]:
        try:
            return read_candidates_file(path), path, True
        except Exception as exc:
            LOGGER.warning("Skip invalid cached JSON %s: %s", path.name, exc)

    raise RuntimeError(f"No valid cached JSON found in {data_dir}")


def build_prompt_items(items: list[dict[str, Any]], timezone_name: str) -> str:
    lines: list[str] = []
    for idx, item in enumerate(items[:MAX_CANDIDATES_FOR_PROMPT], start=1):
        title = clean_text(item.get("title"))
        summary = truncate_text(item.get("summary", ""), 320)
        source = clean_text(item.get("source", ""))
        published_at = clean_text(item.get("published_at", "")) or "未知"
        link = clean_text(item.get("link", ""))
        language = clean_text(item.get("language", ""))
        region = clean_text(item.get("region", ""))
        source_group = clean_text(item.get("source_group", ""))
        source_type = clean_text(item.get("source_type", ""))
        source_quality = clean_text(item.get("source_quality", ""))
        summary_source = clean_text(item.get("summary_source", ""))
        summary_quality = clean_text(item.get("summary_quality", ""))
        category = clean_text(item.get("category", ""))
        topic_tags = item.get("topic_tags", [])
        tags_text = ", ".join(str(tag) for tag in topic_tags if str(tag).strip()) or "N/A"

        if not title or not link:
            continue

        lines.append(
            f"[{idx}]\n"
            f"标题: {title}\n"
            f"来源: {source}\n"
            f"语言: {language or 'unknown'}\n"
            f"区域: {region or 'unknown'}\n"
            f"分组: {source_group or 'unknown'}\n"
            f"来源类型: {source_type or 'unknown'}\n"
            f"来源质量: {source_quality or 'unknown'}\n"
            f"类别: {category or '其他'}\n"
            f"标签: {tags_text}\n"
            f"发布时间: {published_at} ({timezone_name})\n"
            f"链接: {link}\n"
            f"摘要来源: {summary_source or 'unknown'}\n"
            f"摘要质量: {summary_quality or 'unknown'}\n"
            f"摘要: {summary}\n"
        )

    return "\n".join(lines)


def strip_code_fence(text: str) -> str:
    text = text.strip()
    if not text.startswith("```"):
        return text
    lines = text.splitlines()
    if lines and lines[0].startswith("```"):
        lines = lines[1:]
    if lines and lines[-1].strip() == "```":
        lines = lines[:-1]
    return "\n".join(lines).strip()


def extract_json_object_text(text: str) -> str:
    text = strip_code_fence(text)
    if text.startswith("{") and text.endswith("}"):
        return text
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        return text[start : end + 1]
    return text


def parse_litellm_report_json(text: str) -> dict[str, Any]:
    json_text = extract_json_object_text(text)
    try:
        obj = json.loads(json_text)
    except json.JSONDecodeError as exc:
        raise LiteLLMReportParseError("LiteLLM did not return valid JSON report") from exc
    if not isinstance(obj, dict):
        raise LiteLLMReportParseError("LiteLLM JSON root must be an object")
    return obj


def normalize_auto_relevance(value: Any) -> str:
    text = clean_text(value)
    if text in VALID_RELATIONS:
        return text

    lower = text.lower()
    if "直接" in text or "direct" in lower:
        return RELATION_DIRECT
    if "暂无" in text or "无明显" in text or "none" in lower:
        return RELATION_NONE
    return RELATION_INDIRECT



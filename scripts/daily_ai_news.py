def feishu_sign(secret: str) -> tuple[str, str]:
    timestamp = str(int(time.time()))
    string_to_sign = f"{timestamp}\n{secret}"
    hmac_code = hmac.new(
        string_to_sign.encode("utf-8"),
        b"",
        digestmod=hashlib.sha256,
    ).digest()
    sign = base64.b64encode(hmac_code).decode("utf-8")
    return timestamp, sign


def send_feishu_payload(webhook_url: str, payload: dict[str, Any], secret: str | None = None) -> None:
    secret_value = (secret or "").strip()
    send_payload = dict(payload)

    if secret_value:
        timestamp, sign = feishu_sign(secret_value)
        send_payload["timestamp"] = timestamp
        send_payload["sign"] = sign

    resp = http_post_json(webhook_url, send_payload)
    if isinstance(resp, dict) and resp.get("code", 0) != 0:
        raise RuntimeError(f"Feishu error code={resp.get('code')} msg={resp.get('msg')}")


def send_report_with_fallback(webhook_url: str, secret: str | None, report: dict[str, Any]) -> None:
    source_json_name = clean_text(report.get("source_json_name", ""))
    used_fallback_cache = bool(report.get("used_fallback_cache", False))

    interactive_payload = {
        "msg_type": "interactive",
        "card": build_single_interactive_card(
            report=report,
            source_json_name=source_json_name,
            used_fallback_cache=used_fallback_cache,
        ),
    }

    try:
        LOGGER.info("Sending one Feishu interactive card")
        send_feishu_payload(webhook_url, interactive_payload, secret=secret)
        return
    except Exception as exc:
        LOGGER.warning("Interactive card send failed, fallback to post. reason=%s", exc)

    post_payload = build_single_post_payload(
        report=report,
        source_json_name=source_json_name,
        used_fallback_cache=used_fallback_cache,
    )

    try:
        LOGGER.info("Sending one Feishu post message")
        send_feishu_payload(webhook_url, post_payload, secret=secret)
        return
    except Exception as exc:
        LOGGER.warning("Post message send failed, fallback to text. reason=%s", exc)

    text_payload = build_single_text_payload(
        report=report,
        source_json_name=source_json_name,
        used_fallback_cache=used_fallback_cache,
    )
    LOGGER.info("Sending one Feishu text message")
    send_feishu_payload(webhook_url, text_payload, secret=secret)



def main() -> int:
    setup_logging()
    project_root = Path(__file__).resolve().parents[1]
    load_dotenv_file(project_root / ".env")

    timezone_name = os.getenv("TIMEZONE", DEFAULT_TIMEZONE)
    news_max_chars = parse_int_env("NEWS_MAX_CHARS", DEFAULT_NEWS_MAX_CHARS)
    news_top_n = parse_int_env("NEWS_TOP_N", DEFAULT_NEWS_TOP_N)
    max_items_for_llm = parse_int_env("MAX_ITEMS_FOR_LLM", DEFAULT_MAX_ITEMS_FOR_LLM)
    llm_provider = os.getenv("LLM_PROVIDER", DEFAULT_LLM_PROVIDER).strip().lower() or DEFAULT_LLM_PROVIDER
    enable_rule_based_fallback = parse_bool_env(
        "ENABLE_RULE_BASED_FALLBACK",
        DEFAULT_ENABLE_RULE_BASED_FALLBACK,
    )

    tz = get_timezone(timezone_name)
    now_local = datetime.now(tz)
    report_date = (now_local - timedelta(days=1)).date().isoformat()

    webhook_url = os.getenv("FEISHU_WEBHOOK_URL", "").strip()
    if not webhook_url:
        raise RuntimeError("Missing FEISHU_WEBHOOK_URL")
    feishu_secret = os.getenv("FEISHU_BOT_SECRET")

    data_dir = project_root / "data" / "news-candidates"
    if not data_dir.exists():
        error_report = build_error_report(report_date, f"目录不存在：{data_dir.as_posix()}")
        error_report["source_json_name"] = "N/A"
        error_report["used_fallback_cache"] = False
        error_report["learning_source_json_name"] = "N/A"
        error_report["learning_used_fallback_cache"] = False
        send_report_with_fallback(webhook_url, feishu_secret, error_report)
        return 1

    try:
        candidates_payload, source_file, used_fallback_cache = find_candidates_json(data_dir, report_date)
    except Exception as exc:
        LOGGER.info(
            "No fresh news candidates JSON for %s; skip Feishu push silently. detail=%s",
            report_date,
            exc,
        )
        return 0

    if used_fallback_cache:
        LOGGER.info(
            "Fresh news candidates JSON %s.json not found; latest available is %s. Skip Feishu push silently.",
            report_date,
            source_file.name,
        )
        return 0

    items, items_field = select_news_items_for_llm(candidates_payload, max_items_for_llm)

    learning_data_dir = project_root / "data" / "learning-candidates"
    learning_items: list[dict[str, Any]] = []
    learning_source_json_name = "N/A"
    learning_used_fallback_cache = False

    if learning_data_dir.exists():
        try:
            learning_payload, learning_source_file, learning_used_fallback_cache = find_candidates_json(
                learning_data_dir,
                report_date,
            )
            learning_source_json_name = learning_source_file.name
            learning_items, learning_items_field = select_learning_items_for_report(learning_payload)
            LOGGER.info(
                "Loaded learning candidates from %s (%s=%s, fallback_cache=%s)",
                learning_source_file.name,
                learning_items_field,
                len(learning_items),
                learning_used_fallback_cache,
            )
        except Exception as exc:
            LOGGER.warning("Load learning candidates failed: %s", exc)
    else:
        LOGGER.warning("Learning candidates directory not found: %s", learning_data_dir.as_posix())

    selected_learning_item = select_learning_candidate(learning_items, tz)
    if selected_learning_item:
        LOGGER.info(
            "Selected learning resource: %s",
            truncate_text(selected_learning_item.get("title", ""), 100),
        )
    else:
        LOGGER.info("No suitable learning resource selected for today")

    if not items:
        empty_report = build_no_significant_news_report(report_date, source_file.name, selected_learning_item)
        empty_report["source_json_name"] = source_file.name
        empty_report["used_fallback_cache"] = used_fallback_cache
        empty_report["learning_source_json_name"] = learning_source_json_name
        empty_report["learning_used_fallback_cache"] = learning_used_fallback_cache
        send_report_with_fallback(webhook_url, feishu_secret, empty_report)
        return 0

    report: dict[str, Any] | None = None
    used_rule_based_report = False
    if llm_provider == "litellm":
        api_key = os.getenv("LITELLM_API_KEY") or os.getenv("OPENAI_API_KEY")
        base_url = os.getenv("LITELLM_BASE_URL", "").strip()
        model = os.getenv("LITELLM_MODEL", "gpt-5.4").strip() or "gpt-5.4"

        LOGGER.info(
            "Generating report JSON from %s (%s=%s, fallback_cache=%s, learning_items=%s)",
            source_file.name,
            items_field,
            len(items),
            used_fallback_cache,
            len(learning_items),
        )

        if not api_key or not base_url:
            message = "Missing LiteLLM API key or base URL"
            if not enable_rule_based_fallback:
                raise RuntimeError(message)
            LOGGER.warning("%s; use rule-based fallback", message)
        else:
            try:
                report = create_report_json_with_litellm(
                    base_url=base_url,
                    api_key=api_key,
                    model=model,
                    report_date=report_date,
                    timezone_name=timezone_name,
                    news_top_n=news_top_n,
                    news_max_chars=news_max_chars,
                    items=items,
                    source_json_name=source_file.name,
                    used_fallback_cache=used_fallback_cache,
                    selected_learning_item=selected_learning_item,
                    learning_items=learning_items,
                    learning_source_json_name=learning_source_json_name,
                    learning_used_fallback_cache=learning_used_fallback_cache,
                )
            except (TimeoutError, URLError, HTTPError, json.JSONDecodeError, RuntimeError, LiteLLMReportParseError) as exc:
                if not enable_rule_based_fallback:
                    raise
                LOGGER.warning(
                    "LiteLLM report generation failed; use rule-based fallback. reason=%s",
                    exc,
                )
    else:
        if not enable_rule_based_fallback:
            raise RuntimeError(f"Unsupported LLM_PROVIDER: {llm_provider}")
        LOGGER.warning("Unsupported LLM_PROVIDER=%s; use rule-based fallback", llm_provider)

    if report is None:
        report = build_rule_based_report(
            news_items=items[:news_top_n],
            learning_item=selected_learning_item,
            target_date=report_date,
        )
        used_rule_based_report = True

    report = normalize_report_payload(
        raw=report,
        report_date=report_date,
        news_top_n=news_top_n,
        candidate_items=items,
        selected_learning_item=selected_learning_item,
        learning_candidate_items=learning_items,
    )
    report = final_dedupe_top_news(report, news_top_n)
    if used_rule_based_report:
        report["is_rule_based_fallback"] = True
        report["summary"] = build_rule_based_summary(report.get("top_news", []))
    report = shrink_report_for_limit(report, news_max_chars, news_top_n)
    report["news_top_n"] = news_top_n
    report["source_json_name"] = source_file.name
    report["used_fallback_cache"] = used_fallback_cache
    report["learning_source_json_name"] = learning_source_json_name
    report["learning_used_fallback_cache"] = learning_used_fallback_cache

    send_report_with_fallback(webhook_url=webhook_url, secret=feishu_secret, report=report)
    LOGGER.info("Daily report sent successfully")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        LOGGER.error("Run failed: %s", exc)
        raise SystemExit(1)

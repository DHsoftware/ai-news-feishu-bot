def normalize_report_payload(
    raw: dict[str, Any],
    report_date: str,
    news_top_n: int,
    candidate_items: list[dict[str, Any]],
    selected_learning_item: dict[str, Any] | None,
    learning_candidate_items: list[dict[str, Any]],
) -> dict[str, Any]:
    title = clean_text(raw.get("title", "")) or f"AI 科技日报｜{report_date}"

    summary = ensure_list_of_strings(raw.get("summary"))[:5]
    if not summary:
        summary = ["候选新闻已生成，但模型未返回有效摘要。"]

    top_raw = raw.get("top_news")
    if not isinstance(top_raw, list):
        top_raw = []

    candidate_url_set, title_to_url, url_to_source, url_to_category = build_candidate_index(candidate_items)
    top_news: list[dict[str, str]] = []
    for item in top_raw:
        normalized = normalize_top_news_item(
            item,
            candidate_url_set=candidate_url_set,
            title_to_url=title_to_url,
            url_to_source=url_to_source,
            url_to_category=url_to_category,
        )
        if not normalized:
            continue
        top_news.append(normalized)
        if len(top_news) >= max(news_top_n, 1):
            break

    if not top_news:
        top_news = build_fallback_news_from_candidates(candidate_items, news_top_n)

    china_links = {
        normalize_url(clean_text(item.get("link", "")))
        for item in candidate_items
        if isinstance(item, dict) and is_china_candidate(item)
    }
    china_links = {link for link in china_links if link}
    available_china_count = len(china_links)

    desired_china_min = min(2, max(news_top_n, 1), available_china_count)
    if available_china_count > 0 and desired_china_min <= 0:
        desired_china_min = 1

    current_china_count = count_china_news(top_news, china_links)
    if current_china_count < desired_china_min:
        supplements = build_china_fallback_news(candidate_items, desired_china_min - current_china_count)
        existing_links = {normalize_url(clean_text(i.get("source_url", ""))) for i in top_news}
        for candidate in supplements:
            candidate_link = normalize_url(clean_text(candidate.get("source_url", "")))
            if not candidate_link or candidate_link in existing_links:
                continue
            if len(top_news) < max(news_top_n, 1):
                top_news.append(candidate)
            else:
                # Replace the least recent/least specific tail item to keep top N stable.
                top_news[-1] = candidate
            existing_links.add(candidate_link)
            current_china_count += 1
            if current_china_count >= desired_china_min:
                break

    learning_url_set, _, learning_url_to_source, _ = build_candidate_index(learning_candidate_items)
    if selected_learning_item:
        selected_url = normalize_url(clean_text(selected_learning_item.get("link", "")))
        if selected_url:
            learning_url_set.add(selected_url)
            selected_source = clean_text(selected_learning_item.get("source", ""))
            if selected_source:
                learning_url_to_source[selected_url] = selected_source

    codex_learning = normalize_codex_learning(
        value=raw.get("codex_learning"),
        selected_item=selected_learning_item,
        candidate_url_set=learning_url_set,
        url_to_source=learning_url_to_source,
    )

    return {
        "title": title,
        "report_date": report_date,
        "summary": summary,
        "top_news": top_news,
        "codex_learning": codex_learning,
    }


def apply_news_field_limits(report: dict[str, Any], what_max: int, why_max: int, impact_max: int) -> None:
    for item in report.get("top_news", []):
        if not isinstance(item, dict):
            continue
        item["what_happened"] = truncate_text(item.get("what_happened", "") or "仍需观察。", what_max)
        item["why_important"] = truncate_text(item.get("why_important", "") or "仍需观察。", why_max)
        item["auto_impact_brief"] = truncate_text(
            item.get("auto_impact_brief", "") or "对汽车行业的实际影响仍需结合车型与研发节奏观察。",
            impact_max,
        )
        item["title"] = truncate_text(item.get("title", "未命名新闻"), 120)
        item["source_name"] = truncate_text(item.get("source_name", "来源"), 48)


def apply_learning_field_limits(
    report: dict[str, Any],
    learning_point_max: int,
    apply_max: int,
    prompt_max: int,
    note_max: int,
) -> None:
    learning = report.get("codex_learning")
    if not isinstance(learning, dict):
        return

    learning["resource_title"] = truncate_text(learning.get("resource_title", ""), 140)
    learning["resource_type"] = truncate_text(learning.get("resource_type", LEARNING_TYPE_NA), 30)
    learning["source_name"] = truncate_text(learning.get("source_name", "来源"), 60)
    learning["learning_point"] = truncate_text(learning.get("learning_point", ""), learning_point_max)
    learning["how_to_apply"] = truncate_text(learning.get("how_to_apply", ""), apply_max)
    learning["example_prompt"] = truncate_text(learning.get("example_prompt", ""), prompt_max)
    learning["confidence_note"] = truncate_text(
        ensure_metadata_note(learning.get("confidence_note", ""), has_resource=bool(clean_text(learning.get("source_url", "")))),
        note_max,
    )


def estimate_report_size(report: dict[str, Any]) -> int:
    parts = [clean_text(report.get("title", ""))]
    for line in ensure_list_of_strings(report.get("summary")):
        parts.append(line)
    for item in report.get("top_news", []):
        if not isinstance(item, dict):
            continue
        parts.extend(
            [
                clean_text(item.get("title", "")),
                clean_text(item.get("what_happened", "")),
                clean_text(item.get("why_important", "")),
                clean_text(item.get("auto_relevance", "")),
                clean_text(item.get("auto_impact_brief", "")),
                clean_text(item.get("source_name", "")),
            ]
        )

    learning = report.get("codex_learning")
    if isinstance(learning, dict):
        parts.extend(
            [
                clean_text(learning.get("resource_title", "")),
                clean_text(learning.get("resource_type", "")),
                clean_text(learning.get("source_name", "")),
                clean_text(learning.get("learning_point", "")),
                clean_text(learning.get("how_to_apply", "")),
                clean_text(learning.get("example_prompt", "")),
                clean_text(learning.get("confidence_note", "")),
            ]
        )
    return len("\n".join(parts))


def shrink_report_for_limit(report: dict[str, Any], news_max_chars: int, news_top_n: int) -> dict[str, Any]:
    compact = json.loads(json.dumps(report, ensure_ascii=False))
    if not isinstance(compact.get("top_news"), list):
        compact["top_news"] = []

    compact["top_news"] = compact["top_news"][: max(news_top_n, 1)]

    profiles = [
        (120, 120, 100),
        (100, 100, 80),
        (90, 90, 70),
        (80, 80, 60),
    ]

    for what_max, why_max, impact_max in profiles:
        apply_news_field_limits(compact, what_max, why_max, impact_max)
        apply_learning_field_limits(compact, 140, 150, 200, 120)
        if estimate_report_size(compact) <= news_max_chars:
            return compact

    summary = ensure_list_of_strings(compact.get("summary"))
    compact["summary"] = [truncate_text(line, 80) for line in summary[:3]]

    while len(compact["top_news"]) > 1 and estimate_report_size(compact) > news_max_chars:
        compact["top_news"].pop()

    apply_news_field_limits(compact, 80, 80, 60)
    apply_learning_field_limits(compact, 120, 120, 180, 110)
    if estimate_report_size(compact) > news_max_chars:
        compact["summary"] = [truncate_text(line, 60) for line in compact.get("summary", [])[:2]]
        apply_news_field_limits(compact, 70, 70, 50)
        apply_learning_field_limits(compact, 100, 100, 140, 90)

    return compact



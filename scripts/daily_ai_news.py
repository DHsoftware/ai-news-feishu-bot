def load_dotenv_file(path: Path) -> None:
    if not path.exists():
        return

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if not key:
            continue
        if value.startswith(("'", '"')) and value.endswith(("'", '"')) and len(value) >= 2:
            value = value[1:-1]
        os.environ.setdefault(key, value)


def parse_int_env(name: str, default: int) -> int:
    raw = os.getenv(name, str(default)).strip()
    try:
        value = int(raw)
        if value <= 0:
            raise ValueError
        return value
    except ValueError:
        LOGGER.warning("%s invalid (%s), fallback to %s", name, raw, default)
        return default


def parse_nonnegative_int_env(name: str, default: int) -> int:
    raw = os.getenv(name, str(default)).strip()
    try:
        value = int(raw)
        if value < 0:
            raise ValueError
        return value
    except ValueError:
        LOGGER.warning("%s invalid (%s), fallback to %s", name, raw, default)
        return default


def get_timezone(tz_name: str) -> timezone:
    try:
        return ZoneInfo(tz_name)
    except ZoneInfoNotFoundError:
        if tz_name == DEFAULT_TIMEZONE:
            return timezone(timedelta(hours=8), name=tz_name)
        if tz_name.upper() == "UTC":
            return timezone.utc
        raise RuntimeError(f"Invalid TIMEZONE: {tz_name}")


def safe_endpoint_label(url: str) -> str:
    parsed = urlparse(url)
    return parsed.netloc or "unknown-host"


def normalize_url(url: str) -> str:
    value = (url or "").strip()
    if not value:
        return ""
    parsed = urlparse(value)
    tracking_keys = {
        "utm_source",
        "utm_medium",
        "utm_campaign",
        "utm_term",
        "utm_content",
        "fbclid",
        "gclid",
        "spm",
        "from",
        "source",
    }
    query = [
        (key, val)
        for key, val in parse_qsl(parsed.query, keep_blank_values=True)
        if key.lower() not in tracking_keys
    ]
    return urlunparse(
        (
            parsed.scheme.lower(),
            parsed.netloc.lower(),
            parsed.path.rstrip("/"),
            "",
            urlencode(query, doseq=True),
            "",
        )
    )


def clean_text(value: Any) -> str:
    text = str(value or "")
    text = text.replace("\r", "\n")
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def truncate_text(text: str, max_len: int) -> str:
    text = clean_text(text)
    if max_len <= 0:
        return ""
    if len(text) <= max_len:
        return text
    if max_len == 1:
        return text[:1]
    return text[: max_len - 1].rstrip() + "…"


def http_post_json(
    url: str,
    payload: dict[str, Any],
    headers: dict[str, str] | None = None,
    timeout_seconds: int | None = None,
    retry_count: int = 0,
    retry_timeout_seconds: int | None = None,
) -> dict[str, Any]:
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req_headers = {"Content-Type": "application/json"}
    if headers:
        req_headers.update(headers)

    timeout_value = timeout_seconds or parse_int_env("HTTP_TIMEOUT_SECONDS", DEFAULT_HTTP_TIMEOUT_SECONDS)
    retry_timeout_value = retry_timeout_seconds or timeout_value
    attempts = max(retry_count, 0) + 1
    last_exc: Exception | None = None

    for attempt in range(1, attempts + 1):
        attempt_timeout = timeout_value if attempt == 1 else retry_timeout_value
        request = Request(url=url, data=data, headers=req_headers, method="POST")
        try:
            with urlopen(request, timeout=attempt_timeout) as response:
                body = response.read().decode("utf-8", errors="replace")
            break
        except HTTPError as exc:
            body = exc.read().decode("utf-8", errors="replace") if exc.fp else ""
            raise RuntimeError(
                f"HTTP {exc.code} calling endpoint={safe_endpoint_label(url)}: {body[:200]}"
            ) from exc
        except TimeoutError as exc:
            last_exc = exc
            if attempt < attempts:
                LOGGER.warning(
                    "Request timed out calling endpoint=%s after %ss, retry %s/%s",
                    safe_endpoint_label(url),
                    attempt_timeout,
                    attempt,
                    retry_count,
                )
                continue
            raise RuntimeError(
                f"Request timed out calling endpoint={safe_endpoint_label(url)} after {attempt_timeout}s"
            ) from exc
        except URLError as exc:
            last_exc = exc
            if attempt < attempts:
                LOGGER.warning(
                    "Network error calling endpoint=%s, retry %s/%s: %s",
                    safe_endpoint_label(url),
                    attempt,
                    retry_count,
                    exc,
                )
                continue
            raise RuntimeError(f"Network error calling endpoint={safe_endpoint_label(url)}: {exc}") from exc
    else:
        raise RuntimeError(f"Request failed calling endpoint={safe_endpoint_label(url)}: {last_exc}")

    try:
        return json.loads(body) if body else {}
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"Invalid JSON response from endpoint={safe_endpoint_label(url)}: {body[:200]}"
        ) from exc


def ensure_list_of_strings(value: Any) -> list[str]:
    if isinstance(value, str):
        text = clean_text(value)
        return [text] if text else []
    if isinstance(value, list):
        out: list[str] = []
        for item in value:
            text = clean_text(item)
            if text:
                out.append(text)
        return out
    return []


def read_candidates_file(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise RuntimeError(f"Invalid JSON structure: {path.name}")
    items = data.get("curated_items", data.get("items"))
    if not isinstance(items, list):
        raise RuntimeError(f"Invalid JSON curated_items/items list: {path.name}")
    return data


def find_candidates_json(data_dir: Path, target_date: str) -> tuple[dict[str, Any], Path, bool]:
    expected_file = data_dir / f"{target_date}.json"
    if expected_file.exists():
        return read_candidates_file(expected_file), expected_file, False

    candidates = sorted(data_dir.glob("*.json"), reverse=True)
    if not candidates:
        raise RuntimeError(f"No candidates JSON found in {data_dir}")

    for path in candidates[:FALLBACK_SCAN_DAYS]:
        try:
            return read_candidates_file(path), path, True
        except Exception as exc:
            LOGGER.warning("Skip invalid cached JSON %s: %s", path.name, exc)

    raise RuntimeError(f"No valid cached JSON found in {data_dir}")


